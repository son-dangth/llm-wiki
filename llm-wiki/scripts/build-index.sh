#!/bin/bash
# build-index.sh — Regenerate the wiki index from page frontmatter
# Usage: build-index.sh [wiki_root]
# Writes $WIKI_ROOT/.llm-wiki/index.md in the WIKI_SCHEMA.md "Index Format" and
# stores the frontmatter hash in .llm-wiki/cache/index-hash.txt, so that
# check-stale.sh reports the index as fresh.
# Exit: 0 on success, 1 on error

set -euo pipefail

if [ "${1:-}" = "--help" ] || [ "${1:-}" = "-h" ]; then
    echo "Usage: build-index.sh [wiki_root]"
    echo "Regenerate .llm-wiki/index.md from the frontmatter of every page."
    echo "  wiki_root   Wiki directory (default: ./wiki)"
    exit 0
fi

WIKI_ROOT="${1:-./wiki}"
META="$WIKI_ROOT/.llm-wiki"

if [ ! -d "$META" ]; then
    echo "ERROR: '$WIKI_ROOT' is not a wiki (no .llm-wiki/ directory)" >&2
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck disable=SC1091
source "$SCRIPT_DIR/_utils.sh"

# One tab-separated row per page: slug, title, type, language, tags, summary, modified.
# Handles inline lists (tags: [a, b]) and block lists (- a). "|" is escaped for tables.
page_row() {
    local file="$1" slug
    slug=$(basename "$file" .md)
    frontmatter "$file" | awk -v slug="$slug" '
        function clean(v) {
            sub(/^[[:space:]]+/, "", v); sub(/[[:space:]]+$/, "", v)
            if (v ~ /^".*"$/ || v ~ /^\x27.*\x27$/) v = substr(v, 2, length(v) - 2)
            gsub(/\|/, "\\|", v); gsub(/\t/, " ", v)
            return v
        }
        /^---$/ { next }
        /^[A-Za-z_]+:/ {
            key = $0; sub(/:.*/, "", key)
            val = $0; sub(/^[A-Za-z_]+:[[:space:]]*/, "", val)
            in_tags = 0
            if (key == "tags") {
                if (val ~ /^\[/) {
                    gsub(/[\[\]]/, "", val)
                    n = split(val, arr, /,/)
                    for (i = 1; i <= n; i++) { t = clean(arr[i]); if (t != "") tags = tags (tags == "" ? "" : ", ") t }
                } else if (val == "") { in_tags = 1 }
                else { tags = clean(val) }
            } else { f[key] = clean(val) }
            next
        }
        in_tags && /^[[:space:]]*-/ {
            t = $0; sub(/^[[:space:]]*-[[:space:]]*/, "", t); t = clean(t)
            if (t != "") tags = tags (tags == "" ? "" : ", ") t
        }
        END { printf "%s\t%s\t%s\t%s\t%s\t%s\t%s\n", slug, f["title"], f["type"], f["language"], tags, f["summary"], f["modified"] }
    '
}

ROWS=$(list_pages "$WIKI_ROOT" | while IFS= read -r -d '' file; do page_row "$file"; done)
TOTAL=0
[ -n "$ROWS" ] && TOTAL=$(printf '%s\n' "$ROWS" | wc -l | tr -d ' ')
HASH=$(frontmatter_hash "$WIKI_ROOT")
NOW=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
ORPHANS=$(bash "$SCRIPT_DIR/find-orphans.sh" "$WIKI_ROOT" | sed -n 's/^ORPHAN: //p')

# Review queue: one line per pending item of review.json, without needing jq.
# Assumes the objects in "pending" contain no braces in their strings.
review_lines() {
    local file="$META/review.json"
    [ -f "$file" ] || return 0
    tr '\n' ' ' < "$file" | grep -o '{[^{}]*}' | while IFS= read -r obj; do
        local type page desc
        type=$(printf '%s' "$obj" | sed -nE 's/.*"type"[[:space:]]*:[[:space:]]*"([^"]*)".*/\1/p')
        page=$(printf '%s' "$obj" | sed -nE 's/.*"pages?"[[:space:]]*:[[:space:]]*\[?[[:space:]]*"([^"]*)".*/\1/p')
        desc=$(printf '%s' "$obj" | sed -nE 's/.*"description"[[:space:]]*:[[:space:]]*"(([^"\\]|\\.)*)".*/\1/p' | sed 's/\\"/"/g')
        [ -z "$type$desc" ] && continue
        echo "- [[${page:-?}]] — ⚠️ ${type:-item}: $desc"
    done
}

{
    echo "# Wiki Index"
    echo "<!-- AUTO-GENERATED by build-index.sh — DO NOT EDIT BY HAND -->"
    echo "**Last generated:** $NOW"
    echo "**Source hash:** $HASH"
    echo "**Total pages:** $TOTAL"
    echo ""
    echo "## All Pages"
    echo "| Slug | Title | Type | Lang | Tags | Summary | Modified |"
    echo "|------|-------|------|------|------|---------|----------|"
    if [ -n "$ROWS" ]; then
        printf '%s\n' "$ROWS" | awk -F'\t' '{ printf "| [[%s]] | %s | %s | %s | %s | %s | %s |\n", $1, $2, $3, $4, $5, $6, $7 }'
    fi
    echo ""
    echo "## By Tag"
    if [ -n "$ROWS" ]; then
        printf '%s\n' "$ROWS" | awk -F'\t' '{
            n = split($5, t, /, /)
            for (i = 1; i <= n; i++) if (t[i] != "") printf "%s\t%s\t%s\n", t[i], $1, $6
        }' | LC_ALL=C sort -t$'\t' -k1,1 -k2,2 | awk -F'\t' '
            { tag[NR] = $1; line[NR] = "- [[" $2 "]] — " $3; count[$1]++ }
            END {
                for (i = 1; i <= NR; i++) {
                    if (tag[i] != prev) {
                        if (i > 1) print ""
                        printf "### %s (%d pages)\n", tag[i], count[tag[i]]
                        prev = tag[i]
                    }
                    print line[i]
                }
            }'
    else
        echo "*No pages yet.*"
    fi
    echo ""
    echo "## Orphan Pages / 孤立页面"
    if [ -n "$ORPHANS" ]; then
        printf '%s\n' "$ORPHANS" | sed 's/.*/- [[&]] — no incoming links/'
    else
        echo "*None.*"
    fi
    echo ""
    echo "## Review Queue / 审核队列"
    REVIEW=$(review_lines)
    if [ -n "$REVIEW" ]; then
        printf '%s\n' "$REVIEW"
    else
        echo "*No pending reviews.*"
    fi
} > "$META/index.md"

mkdir -p "$META/cache"
echo "$HASH" > "$META/cache/index-hash.txt"

echo "Index written: $META/index.md ($TOTAL pages, $(printf '%s' "$ORPHANS" | grep -c . || true) orphans)"
